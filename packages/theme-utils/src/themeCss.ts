// Builds the CSS variables for every palette. Data in, text out, no imports of values, so plain Node can run it
// (packages/app/scripts/generate-theme-css.mjs) and the Jest test can check the committed file against it.
import type { Palette, ThemeId } from './palettes';

type Rgb = [number, number, number];
const rgb = (hex: string): Rgb => {
  const n = parseInt(hex.slice(1), 16);
  return [(n >> 16) & 255, (n >> 8) & 255, n & 255];
};
const hex = (c: Rgb) => `#${c.map(v => Math.round(v).toString(16).padStart(2, '0')).join('')}`;
/** `t` of the way from a to b. */
export const mix = (a: string, b: string, t: number) => {
  const x = rgb(a);
  const y = rgb(b);
  return hex([x[0] + (y[0] - x[0]) * t, x[1] + (y[1] - x[1]) * t, x[2] + (y[2] - x[2]) * t]);
};
const rgba = (h: string, alpha: number) => `rgba(${rgb(h).join(',')},${alpha})`;

export function variablesFor(p: Palette): Record<string, string> {
  const dark = p.isDark;
  const v: Record<string, string> = {
    // @backstage/ui
    '--bui-bg-app': p.bg,
    '--bui-bg-neutral-1': p.surface,
    '--bui-bg-neutral-1-hover': p.avatarBg,
    '--bui-bg-neutral-1-pressed': p.hoverBg,
    '--bui-bg-neutral-2': p.avatarBg,
    '--bui-bg-neutral-2-hover': p.hoverBg,
    '--bui-bg-neutral-2-pressed': p.border,
    '--bui-bg-neutral-3': p.hoverBg,
    '--bui-bg-neutral-3-hover': p.border,
    '--bui-bg-neutral-3-pressed': p.borderHover,
    '--bui-bg-neutral-4': p.border,
    '--bui-bg-neutral-4-hover': p.borderHover,
    '--bui-bg-solid': p.text,
    '--bui-bg-solid-hover': dark ? '#ffffff' : mix(p.text, '#ffffff', 0.2),
    '--bui-bg-solid-pressed': mix(p.text, '#000000', 0.1),
    '--bui-fg-primary': p.text,
    '--bui-fg-secondary': p.textSecondary,
    '--bui-fg-disabled': p.textDisabled,
    '--bui-fg-solid': dark ? p.bg : '#ffffff',
    '--bui-border-1': p.border,
    '--bui-border-2': p.borderHover,
    '--bui-ring': p.blue,
    '--bui-scrollbar': rgba(p.border, 0.5),
    '--bui-scrollbar-thumb': p.borderHover,
    '--bui-shadow': dark ? 'none' : '0 4px 16px rgba(0,0,0,0.08)',
    // Geist
    '--ds-background-100': p.surface,
    '--ds-background-200': p.bg,
    '--ds-gray-100': p.avatarBg,
    '--ds-gray-200': p.hoverBg,
    '--ds-gray-300': mix(p.hoverBg, p.border, 0.5),
    '--ds-gray-400': p.border,
    '--ds-gray-500': p.borderHover,
    '--ds-gray-600': p.textMuted,
    '--ds-gray-700': p.textMuted,
    '--ds-gray-900': p.textSecondary,
    '--ds-gray-1000': p.text,
    '--ds-gray-alpha-100': dark ? '#ffffff0f' : '#0000000d',
    '--ds-gray-alpha-200': dark ? '#ffffff17' : '#00000015',
    '--ds-gray-alpha-300': dark ? '#ffffff21' : '#0000001a',
    '--ds-gray-alpha-400': dark ? '#ffffff24' : '#00000014',
    '--ds-gray-alpha-500': dark ? '#ffffff3d' : '#00000036',
    '--fg-primary': p.text,
    '--fg-secondary': p.textSecondary,
    '--fg-tertiary': p.textMuted,
    '--fg-disabled': p.textDisabled,
    '--border': p.border,
    '--border-hover': p.borderHover,
    '--surface': p.surface,
    '--surface-hover': dark ? p.avatarBg : p.bg,
    '--blue': p.blue,
    '--blue-dark': dark ? '#0070f3' : mix(p.blue, '#000000', 0.1),
  };
  return { ...v, ...(p.css ?? {}) };
}

/** The sidebar is always a dark surface: it wears the colours of the palette named by `sidebar`. */
export function sidebarVariablesFor(p: Palette): Record<string, string> {
  return {
    '--bui-bg-app': p.bg,
    '--bui-bg-neutral-1': p.surface,
    '--bui-bg-neutral-1-hover': p.avatarBg,
    '--bui-bg-neutral-1-pressed': p.hoverBg,
    '--bui-fg-primary': p.text,
    '--bui-fg-secondary': p.textSecondary,
    '--bui-fg-disabled': p.textDisabled,
    '--bui-border-1': p.border,
  };
}

const block = (selector: string, vars: Record<string, string>) =>
  `${selector} {\n${Object.entries(vars).map(([k, val]) => `  ${k}: ${val};`).join('\n')}\n}\n`;

export function buildThemeCss(palettes: Record<ThemeId, Palette>, ids: ThemeId[]): string {
  const out = [
    '/* GENERATED by packages/app/scripts/generate-theme-css.mjs from packages/theme-utils/src/palettes.ts.',
    '   Do not edit by hand: run `yarn workspace app themes:css`. A test fails if this file is stale.',
    '   The class on <html> is "theme-dark|theme-light tv-<id>"; bare <html> (before React) is the default light theme. */',
    '',
  ];
  for (const id of ids) {
    const p = palettes[id];
    const selector = id === 'light' ? 'html,\nhtml.tv-light' : `html.tv-${id}`;
    out.push(`/* ${p.name} */`, block(selector, variablesFor(p)));
    out.push(block(`html.tv-${id} .sidebar-dark-theme`, sidebarVariablesFor(palettes[p.sidebar])));
  }
  return out.join('\n');
}
